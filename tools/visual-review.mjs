await page.getByRole('button',{name:'Back to adventures',exact:true}).click();
await capture('mobile-adventures');
await page.locator('.mobile-nav').getByRole('button',{name:'Settings',exact:true}).click();
await capture('mobile-settings');
await page.locator('.mobile-nav').getByRole('button',{name:'Discover',exact:true}).click();
await capture('mobile-home-resume');
for(const width of [320,360,768,1440]){
  await page.setViewportSize({width,height:900});
  await capture(`home-${width}`);
  await page.locator(width<=850?'.mobile-nav':'.sidebar nav').getByRole('button',{name:'Scenarios',exact:true}).click();
  await capture(`scenarios-${width}`);
  await page.getByRole('button',{name:/The Lantern Hollow/}).click();
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  await capture(`editor-${width}`);
  await page.locator(width<=850?'.mobile-nav':'.sidebar nav').getByRole('button',{name:'Discover',exact:true}).click();
}
assert.deepEqual(issues,[]);
console.log('Visual review: 26 captures, no horizontal overflow at 320, 360, 390, 768 or 1440px; no page errors.');
await browser.close();
